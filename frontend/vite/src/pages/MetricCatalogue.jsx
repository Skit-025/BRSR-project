const CATEGORY_CFG = {
  Environmental: { icon: Leaf,    color: 'var(--emerald-400)', badge: 'badge-green' },
  Social:        { icon: Users,   color: 'var(--sky-400)',     badge: 'badge-sky'   },
  Governance:    { icon: Shield,  color: 'var(--brand-400)',   badge: 'badge-brand' },
};

export default function MetricCatalogue() {
  const { data, isLoading } = useMetricCatalogue();
  const metrics = data || MOCK_CATALOGUE;

  const [search,   setSearch]   = useState('');
  const [catFilter, setCatFilter] = useState('All');
  const [expanded, setExpanded] = useState(null);

  const categories = ['All', 'Environmental', 'Social', 'Governance'];
  const filtered = metrics.filter((m) => {
    const matchCat = catFilter === 'All' || m.category === catFilter;
    const matchQ   = !search || m.name.toLowerCase().includes(search.toLowerCase()) ||
                     m.code.toLowerCase().includes(search.toLowerCase());
    return matchCat && matchQ;
  });

  const grouped = {};
  filtered.forEach((m) => {
    if (!grouped[m.category]) grouped[m.category] = [];
    grouped[m.category].push(m);
  });

  return (
    <div className="page-content anim-fade">
      <div className="page-header">
        <div>
          <h1 className="page-title">Metric Catalogue</h1>
          <p className="page-subtitle">{metrics.length} BRSR indicators · ESG, Social, Governance</p>
        </div>
        <div className="page-actions">
          <span className="badge badge-amber">SEBI BRSR Core</span>
          <span className="badge badge-green">{metrics.filter(m => m.mandatory).length} Mandatory</span>
        </div>
      </div>

      {/* Filters */}
      <div className="card">
        <div className="card-body" style={{ padding: '14px 20px' }}>
          <div className="flex gap-3 items-center" style={{ flexWrap: 'wrap' }}>
            <div className="header-search" style={{ width: 280 }}>
              <Search size={13} color="var(--text-muted)" />
              <input placeholder="Search by name or code…" value={search} onChange={e => setSearch(e.target.value)} />
            </div>
            <div className="tabs" style={{ flex: 1, maxWidth: 400 }}>
              {categories.map((c) => (
                <button key={c} className={`tab-btn ${catFilter === c ? 'active' : ''}`}
                  onClick={() => setCatFilter(c)}>{c}</button>
              ))}
            </div>
            <span style={{ marginLeft: 'auto', fontSize: 12, color: 'var(--text-secondary)' }}>
              {filtered.length} results
            </span>
          </div>
        </div>
      </div>

      {/* Metric groups */}
      {Object.entries(grouped).map(([cat, items]) => {
        const cfg = CATEGORY_CFG[cat] || { icon: BookOpen, color: 'var(--text-secondary)', badge: 'badge-gray' };
        const Icon = cfg.icon;
        return (
          <div key={cat} className="card">
            <div className="card-header">
              <div className="flex items-center gap-2">
                <Icon size={15} color={cfg.color} />
                <div className="card-title">{cat}</div>
                <span className={`badge ${cfg.badge}`}>{items.length}</span>
              </div>
            </div>
            <div className="table-wrap">
              <table>
                <thead>
                  <tr>
                    <th style={{ width: 70 }}>Code</th>
                    <th>Indicator</th>
                    <th>Section</th>
                    <th>Unit</th>
                    <th>Source</th>
                    <th>Frequency</th>
                    <th>Required</th>
                    <th style={{ width: 40 }}></th>
                  </tr>
                </thead>
                <tbody>
                  {items.map((m) => (
                    <>
                      <tr key={m.id} style={{ cursor: 'pointer' }} onClick={() => setExpanded(expanded === m.id ? null : m.id)}>
                        <td><span className="mono" style={{ color: cfg.color, fontWeight: 600 }}>{m.code}</span></td>
                        <td style={{ fontWeight: 500 }}>{m.name}</td>
                        <td className="muted" style={{ fontSize: 11 }}>{m.section}</td>
                        <td><span className="badge badge-gray">{m.unit}</span></td>
                        <td>
                          <span className={`badge ${m.source_type === 'direct' ? 'badge-green' : m.source_type === 'derived' ? 'badge-sky' : 'badge-amber'}`}>
                            {m.source_type}
                          </span>
                        </td>
                        <td className="muted">{m.frequency}</td>
                        <td>
                          {m.mandatory
                            ? <span className="badge badge-red">Mandatory</span>
                            : <span className="badge badge-gray">Optional</span>}
                        </td>
                        <td>
                          {expanded === m.id ? <ChevronUp size={13} color="var(--text-muted)" /> : <ChevronDown size={13} color="var(--text-muted)" />}
                        </td>
                      </tr>
                      {expanded === m.id && (
                        <tr key={`${m.id}-exp`}>
                          <td colSpan={8}>
                            <div className="alert alert-info" style={{ margin: '4px 0' }}>
                              <Info size={14} />
                              <span>{m.description}</span>
                            </div>
                          </td>
                        </tr>
                      )}
                    </>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        );
      })}
    </div>
  );
}
