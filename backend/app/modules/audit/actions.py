"""
app/modules/audit/actions.py
Standardized action codes for the immutable audit trail.
"""
from enum import Enum


class AuditAction(str, Enum):
    # Authentication & Access
    USER_LOGIN = "USER_LOGIN"
    USER_LOGOUT = "USER_LOGOUT"
    PERMISSION_DENIED = "PERMISSION_DENIED"

    # Hierarchy & Configuration
    ORG_NODE_CREATED = "ORG_NODE_CREATED"
    ORG_NODE_UPDATED = "ORG_NODE_UPDATED"
    APPLICABILITY_OVERRIDDEN = "APPLICABILITY_OVERRIDDEN"

    # Submission & Data Collection
    SUBMISSION_CREATED = "SUBMISSION_CREATED"
    SUBMISSION_UPDATED = "SUBMISSION_UPDATED"
    SUBMISSION_SUBMITTED = "SUBMISSION_SUBMITTED"
    SUBMISSION_APPROVED = "SUBMISSION_APPROVED"
    SUBMISSION_REJECTED = "SUBMISSION_REJECTED"
    DATAPOINT_UPDATED = "DATAPOINT_UPDATED"

    # Evidence
    EVIDENCE_UPLOADED = "EVIDENCE_UPLOADED"
    EVIDENCE_DELETED = "EVIDENCE_DELETED"
    EVIDENCE_VERIFIED = "EVIDENCE_VERIFIED"

    # Calculations & Aggregations
    CALCULATION_RUN = "CALCULATION_RUN"
    AGGREGATION_RUN = "AGGREGATION_RUN"
    CONSOLIDATION_OVERRIDE = "CONSOLIDATION_OVERRIDE"

    # Period Closing & Snapshots
    PERIOD_LOCKED = "PERIOD_LOCKED"
    SNAPSHOT_CREATED = "SNAPSHOT_CREATED"
    SNAPSHOT_SEALED = "SNAPSHOT_SEALED"
    RESTATEMENT_APPLIED = "RESTATEMENT_APPLIED"

    # Reporting & Export
    REPORT_GENERATED = "REPORT_GENERATED"
    AUDIT_PACK_EXPORTED = "AUDIT_PACK_EXPORTED"
